/// A C build for KeyOS: newlib's headers with the ABI of the
/// armv7a-unknown-xous-elf Rust target (Thumb-2, hard-float NEON, PIE, no
/// unaligned access). cc doesn't know the target, so everything is set here.
fn keyos_build() -> cc::Build {
    let mut build = cc::Build::new();
    build
        .compiler("arm-none-eabi-gcc")
        .archiver("arm-none-eabi-ar")
        .no_default_flags(true)
        .flag("-O2")
        .flag("-mthumb")
        .flag("-march=armv7-a")
        .flag("-mfpu=neon-vfpv4")
        .flag("-mfloat-abi=hard")
        .flag("-mno-unaligned-access")
        .flag("-fPIE")
        // Turns newlib's FILE-peeking stdio macros back into shim calls.
        .flag("-include")
        .flag("csrc/dg_libc.h")
        // No C++ exceptions here; unwind tables would pull in an undefined
        // __aeabi_unwind_cpp_pr0.
        .flag("-fno-unwind-tables")
        .flag("-fno-asynchronous-unwind-tables")
        .flag("-ffunction-sections")
        .flag("-fdata-sections");
    build
}

fn build_doom() {
    let device = std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("xous");
    let mut build = if device { keyos_build() } else { cc::Build::new() };
    if device {
        // The libc shim is its own library: GCC must not turn its loops into
        // calls to the very functions they implement.
        keyos_build()
            .flag("-fno-builtin")
            .flag("-fno-tree-loop-distribute-patterns")
            .warnings(false)
            .file("csrc/libc_shim.c")
            .compile("dglibc");
    } else {
        // Simulator: run the engine on the same shim, renamed to shim_* so
        // the host libc is left alone (see csrc/dg_libc.h).
        build
            .define("DG_HOSTED", None)
            .flag("-include")
            .flag("csrc/dg_libc.h")
            .file("csrc/libc_shim.c");
    }
    build
        .include(DOOM_DIR)
        .define("DOOMGENERIC_RESX", "320")
        .define("DOOMGENERIC_RESY", "200")
        .define("NORMALUNIX", None)
        .define("LINUX", None)
        .define("_DEFAULT_SOURCE", None)
        // Config load/save, which doomgeneric compiles out (patched m_config.c).
        .define("DG_PERSIST_CONFIG", None)
        .opt_level(2)
        .warnings(false)
        .flag_if_supported("-w")
        .file("csrc/w_file_rust.c")
        .file("csrc/dg_haptics.c");
    for src in DOOM_SOURCES {
        build.file(format!("{DOOM_DIR}/{src}"));
    }
    build.compile("doomgeneric");

    println!("cargo:rerun-if-changed=csrc");
    println!("cargo:rerun-if-changed={DOOM_DIR}");
}

fn main() {
    // Themes are generated by the Foundation CLI and pulled in at compile time
    // via foundation_themes::include_theme! (see src/theme.rs).
    //
    // Resolve the generated-theme directory (the FOUNDATION_THEMES_RUST_DIR
    // override that `foundation build`/`sim` set, otherwise the default cache
    // location) and re-export it through cargo:rustc-env so the include_theme!
    // env!() always sees it, independent of how the ambient build environment
    // is set up.
    let themes_rust_dir = std::env::var("FOUNDATION_THEMES_RUST_DIR").unwrap_or_else(|_| {
        let home = std::env::var("HOME").unwrap_or_else(|_| ".".to_string());
        format!("{home}/.foundation/themes/rust")
    });
    println!("cargo:rustc-env=FOUNDATION_THEMES_RUST_DIR={themes_rust_dir}");
    println!("cargo:rerun-if-env-changed=FOUNDATION_THEMES_RUST_DIR");

    build_doom();

    compile_options(CompileOptions {
        module_path: "ui/app.slint",
        include_slint: true,
        include_router: false,
        include_translations: false,
        include_time_localization: false,
    });
}
